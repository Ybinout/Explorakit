CREATE TABLE IF NOT EXISTS dark_ko_resolutions (
 user_id INT NOT NULL, faint_id CHAR(36) NOT NULL, pokemon_uuid CHAR(36) NOT NULL,
 outcome ENUM('lost','survived','kit') NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,faint_id), CONSTRAINT fk_dark_ko_owner FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS whitepeak_tournaments (
 id CHAR(36) NOT NULL PRIMARY KEY, host_id INT NOT NULL, phase VARCHAR(20) NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1, snapshot LONGTEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_whitepeak_tournament_host FOREIGN KEY(host_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
