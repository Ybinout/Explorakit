const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const enabled = process.env.RUN_MYSQL_TESTS === '1';
let db, users, teams, items, pc, factory, engine, owner, pokemon;
test.before(async () => {
    if (!enabled) return;
    if (process.env.DB_NAME !== 'explorakit_test') throw Error('Dedicated test database required');
    db = require('../server/config/database').dbPool;
    users = require('../server/persistence/userRepository');
    teams = require('../server/persistence/teamRepository');
    items = require('../server/persistence/itemRepository');
    pc = require('../server/persistence/pokemonStorageRepository');
    factory = require('../server/game/drift/pokemonFactory');
    engine = require('../server/game/battle/battleEngine');
    owner = await users.createUserWithStarter('toxic_orb_' + randomUUID(), randomUUID(), { starterId: 7 });
    pokemon = factory.create(472, 50, true);
    pokemon.passiveAbility = 'Poison Heal';
    pokemon.currentHp = Math.floor(pokemon.maxHp / 2);
    await teams.editEquipe(owner.id, { pokemons: [pokemon] });
    await db.execute('UPDATE users SET money=20000 WHERE id=?', [owner.id]);
});
test.after(async () => {
    if (owner) await db.execute('DELETE FROM users WHERE id=?', [owner.id]);
    await db?.end();
});
test('SQL Toxic Orb: real badge guard, 10000 price, inventory and held item persist', { skip: !enabled }, async () => {
    const locked = await items.purchaseUserItem(owner.id, 'toxic_orb', 1, { mapName: 'tour_etage2', flags: { hoze_defeated: 'true' }, price: 1 });
    assert.equal(locked.reason, 'badge_required');
    assert.equal(Number((await db.execute('SELECT money FROM users WHERE id=?', [owner.id]))[0][0].money), 20000);
    await db.execute("INSERT INTO player_story_flags(user_id,flag_key,flag_value) VALUES(?,'hoze_defeated','true')", [owner.id]);
    const purchased = await items.purchaseUserItem(owner.id, 'toxic_orb', 1, { mapName: 'tour_etage2', price: 1 });
    assert.equal(purchased.success, true);
    assert.equal(purchased.money, 10000);
    assert.equal(purchased.items.find(i => i.key === 'toxic_orb').quantity, 1);
    const team = await teams.getTeamRecord(owner.id);
    await items.equipHeldItem(owner.id, team.id, pokemon.uuid, 'toxic_orb');
    const loaded = (await teams.loadEquipe(owner.id)).pokemons[0];
    assert.equal(loaded.heldItem, 'toxic_orb');
    assert.equal(loaded.currentHp, pokemon.currentHp);
    assert.equal(loaded.passiveAbility, 'Poison Heal');
    assert.equal((await items.loadUserItems(owner.id)).find(i => i.key === 'toxic_orb')?.quantity || 0, 0);
});
test('SQL Toxic Orb: activated poison, healing and nonconsumed item survive battle save and PC retrieval', { skip: !enabled }, async () => {
    const loaded = (await teams.loadEquipe(owner.id)).pokemons[0], enemy = factory.create(143, 50, true);
    enemy.passiveAbility = null; enemy.heldItem = null;
    const state = engine.createBattleState(), hp = loaded.currentHp;
    engine.processEndOfRound(loaded, enemy, state.sides.player, state.sides.enemy, state);
    assert.equal(loaded.status, 'badly_poison');
    assert.equal(loaded.currentHp, hp);
    engine.processEndOfRound(loaded, enemy, state.sides.player, state.sides.enemy, state);
    assert.equal(loaded.currentHp, hp + Math.floor(loaded.maxHp / 8));
    require('../server/game/battle/battleOutcome').clearBattleTransientState([loaded]);
    await teams.editEquipe(owner.id, { pokemons: [loaded] });
    const saved = (await teams.loadEquipe(owner.id)).pokemons[0];
    assert.equal(saved.heldItem, 'toxic_orb');
    assert.equal(saved.status, 'badly_poison');
    assert.equal(saved.currentHp, loaded.currentHp);
    await teams.editEquipe(owner.id, { pokemons: [factory.create(7, 5, true)] });
    await pc.storeCapturedPokemon(owner.id, saved);
    const result = await pc.mutateStorage(owner.id, { action: 'takeItem', source: 'box', pokemonUuid: saved.uuid, expectedItem: 'toxic_orb' });
    assert.equal(result.takenItem, 'toxic_orb');
    const stored = result.state.entries.find(e => e.pokemon.uuid === saved.uuid).pokemon;
    assert.equal(stored.heldItem, null);
    assert.equal(stored.currentHp, saved.currentHp);
    assert.equal(stored.status, 'badly_poison');
    assert.equal((await items.loadUserItems(owner.id)).find(i => i.key === 'toxic_orb').quantity, 1);
});
