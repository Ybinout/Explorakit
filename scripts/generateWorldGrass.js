// Visual metadata only: never rewrites author maps, collisions or PNG artwork.
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..'),OUTPUT=path.join(ROOT,'vue-explorakit/src/data/worldGrass.js');
// teset2 2961: snow-covered blades on Routes 13/14, not the snowy ground.
const GRASS_IDS=new Set([3225,2804,2944,3087,2961]);
const TECHNICAL=new Set(['coll','battle','change','int','foreground','forground','for','for2','leaf','Calque de Tuiles 11']);
function buildGrassProfiles(root=ROOT){
 const profiles={};
 for(const filename of fs.readdirSync(path.join(root,'data/maps')).filter(n=>n.endsWith('.json')).sort()){
  const map=JSON.parse(fs.readFileSync(path.join(root,'data/maps',filename),'utf8'));
  const tileset=map.tilesets?.find(t=>t.name==='teset2'||/(?:^|\/)teset2\.tsx$/.test(t.source||''));
  if(!tileset||map.width!==28||map.height!==20||map.tilewidth!==16||map.tileheight!==16)continue;
  const coll=map.layers.find(l=>l.name==='coll')?.data,visual=map.layers.filter(l=>l.type==='tilelayer'&&!TECHNICAL.has(l.name));
  const cells=[];
  for(let i=0;i<map.width*map.height;i++){
   if(coll?.[i])continue;
   let grass=0;
   for(const layer of visual){const gid=(Number(layer.data?.[i])>>>0)&0x0fffffff,local=gid-tileset.firstgid+1;if(GRASS_IDS.has(local))grass=local;}
   if(grass)cells.push([i,grass]);
  }
  if(cells.length)profiles[filename.slice(0,-5)]=cells;
 }
 const aliases=JSON.parse(fs.readFileSync(path.join(root,'data/game/mapAliases.json'),'utf8')).aliases;
 for(const [alias,source]of Object.entries(aliases))if(profiles[source])profiles[alias]=profiles[source];
 return profiles;
}
function serialize(profiles){return '// Generated by scripts/generateWorldGrass.js; read-only visual high-grass cells.\nexport default '+JSON.stringify(profiles,null,2)+';\n';}
if(require.main===module){const generated=serialize(buildGrassProfiles());if(process.argv.includes('--check')){if(fs.readFileSync(OUTPUT,'utf8')!==generated)throw Error('World grass metadata is stale; regenerate it.');}else fs.writeFileSync(OUTPUT,generated);console.log('Grass metadata: '+Object.keys(buildGrassProfiles()).length+' maps, author files unchanged.');}
module.exports={buildGrassProfiles,serialize,GRASS_IDS,TECHNICAL};
