// Read-only terrain metadata: author maps, collisions and artwork stay intact.
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..'),OUTPUT=path.join(ROOT,'vue-explorakit/src/data/dirtGround.js');
// Two authored teset2 path families: grey-brown earth and pale ochre soil.
const DIRT_IDS=new Set([2117,2118,2119,2257,2258,2259,2397,2398,2399,2537,2538,2677,
 2102,2103,2104,2242,2243,2244,2382,2383,2384,2523,2524]);
const COLORS=['149,135,115','143,124,104','127,110,90','160,148,133','123,103,93',
 '233,219,172','207,204,108','247,237,204'];
const TECHNICAL=new Set(['coll','battle','change','int','foreground','forground','for','for2','for3','leaf','Calque de Tuiles 11']);
function buildDirtGround(root=ROOT){
 const maps={};
 for(const filename of fs.readdirSync(path.join(root,'data/maps')).sort()){
  const name=filename.replace(/\.json$/,'');
  if(!filename.endsWith('.json')||!/^(?:start|ville(?:_safe)?\d+|gen_ville\d+|(?:gen_)?route\d+|pk[12])$/.test(name))continue;
  const map=JSON.parse(fs.readFileSync(path.join(root,'data/maps',filename),'utf8'));
  const tileset=map.tilesets?.find(t=>t.name==='teset2'||/(?:^|\/)teset2\.tsx$/.test(t.source||''));
  if(!tileset||map.width!==28||map.height!==20||map.tilewidth!==16||map.tileheight!==16)continue;
  const coll=map.layers.find(l=>l.name==='coll')?.data,layers=map.layers.filter(l=>l.type==='tilelayer'&&!TECHNICAL.has(l.name));
  const rows=Array.from({length:20},(_,y)=>Array.from({length:28},(_,x)=>{
   const i=y*28+x;return coll?.[i]===0&&layers.some(l=>DIRT_IDS.has(((Number(l.data?.[i])>>>0)&0x0fffffff)-tileset.firstgid+1))?'1':'0';
  }).join(''));
  if(rows.some(r=>r.includes('1')))maps[name]=rows;
 }
 return {maps,colors:COLORS};
}
function serialize(data){return '// Generated by scripts/generateDirtGround.js; soil candidates plus exact rendered earth colours.\nexport default '+JSON.stringify(data,null,2)+';\n';}
if(require.main===module){const data=buildDirtGround(),text=serialize(data);if(process.argv.includes('--check')){if(fs.readFileSync(OUTPUT,'utf8')!==text)throw Error('Dirt metadata is stale.');}else fs.writeFileSync(OUTPUT,text);console.log('Dirt profiles: '+Object.keys(data.maps).length+' outdoor maps; author files unchanged.');}
module.exports={buildDirtGround,serialize,DIRT_IDS,COLORS,TECHNICAL};
