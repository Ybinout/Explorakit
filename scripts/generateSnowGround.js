// Read-only visual metadata: never changes author maps, tiles or collisions.
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const OUTPUT=path.join(ROOT,'vue-explorakit/src/data/snowGround.js');
function buildSnowGround(root=ROOT){
    const profiles={};
    for(const name of ['route13','route14','ville5']){
        const map=JSON.parse(fs.readFileSync(path.join(root,'data/maps',name+'.json'),'utf8'));
        const tileset=map.tilesets.find(t=>t.name==='teset2');
        const ground=map.layers.find(l=>l.name==='sol'),coll=map.layers.find(l=>l.name==='coll');
        if(!tileset||map.width!==28||map.height!==20)throw Error('Unexpected snow map: '+name);
        profiles[name]=Array.from({length:20},(_,y)=>Array.from({length:28},(_,x)=>{
            const i=y*28+x,local=(ground.data[i]&0x0fffffff)-tileset.firstgid+1;
            return local===2261&&!coll.data[i]?'1':'0';
        }).join(''));
    }
    return profiles;
}
function serialize(profiles){return '// Generated by scripts/generateSnowGround.js; walkable snow-base cells only.\nexport default '+JSON.stringify(profiles,null,2)+';\n';}
if(require.main===module){const data=serialize(buildSnowGround());if(process.argv.includes('--check')){if(fs.readFileSync(OUTPUT,'utf8')!==data)throw Error('Snow ground metadata is stale.');}else fs.writeFileSync(OUTPUT,data);console.log('Snow ground: 3 maps; author files unchanged.');}
module.exports={buildSnowGround,serialize};
