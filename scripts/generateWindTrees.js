// Read-only masks from authored tree tiles. Never moves or rewrites map artwork.
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..'),OUTPUT=path.join(ROOT,'vue-explorakit/src/data/windTrees.js');
const TILE_PARTS=new Map();
function row(ids,y,offset=0){ids.forEach((id,x)=>TILE_PARTS.set(id,[x+offset,y]));}
row([29,30,31],0);row([169,170,171],1);
row([450,451,452,453],0);row([590,591,592,593],1);row([730,731,732,733],2);
row([607,608],0,1);row([746,747,748,749],1);row([886,887,888,889],2);
const TECHNICAL=new Set(['coll','battle','change','int','liaisons']);
function build(root=ROOT){
 const profiles={},climates=JSON.parse(fs.readFileSync(path.join(root,'data/game/map_weather.json'))),aliases=JSON.parse(fs.readFileSync(path.join(root,'data/game/mapAliases.json'))).aliases;
 for(const[map,climate]of Object.entries(climates)){
  if(!climate.ambience?.wind)continue;
  const data=JSON.parse(fs.readFileSync(path.join(root,'data/maps',(aliases[map]||map)+'.json'))),tileset=data.tilesets.find(t=>t.name==='teset2'||/(?:^|\/)teset2\.tsx$/.test(t.source||''));if(!tileset)continue;
  const profile={};
  for(const layer of ['background','foreground']){
   if(map==='start'&&layer==='foreground')continue; // Existing hand-mapped village crowns use the baked leaf atlas.
   const cells=Array(560).fill(0);
   for(const l of data.layers){if(l.type!=='tilelayer'||TECHNICAL.has(l.name))continue;const foreground=/^(?:foreground|forground|for2|for3|leaf)$/.test(l.name);if(foreground!==(layer==='foreground'))continue;l.data.forEach((gid,i)=>{if(gid)cells[i]=((gid>>>0)&0x0fffffff)-tileset.firstgid+1;});}
   const crowns=[],indices=[],owners=new Map();
   cells.forEach((gid,i)=>{const part=TILE_PARTS.get(gid);if(!part)return;const x=i%28,y=Math.floor(i/28),left=(x-part[0])*16,top=(y-part[1])*16,key=left+':'+top;let owner=owners.get(key);if(owner===undefined){owner=crowns.length;owners.set(key,owner);crowns.push({left,top,right:left+(gid<=171?48:64),bottom:top+(gid<=171?32:48)});}indices.push([i,owner]);});
   if(indices.length)profile[layer]={crowns,cells:indices};
  }
  if(Object.keys(profile).length)profiles[map]=profile;
 }
 return profiles;
}
if(require.main===module){const text='// Generated by scripts/generateWindTrees.js; exact authored tree crown cells.\nexport default '+JSON.stringify(build(),null,2)+';\n';if(process.argv.includes('--check')){if(fs.readFileSync(OUTPUT,'utf8')!==text)throw Error('Wind tree metadata is stale.');}else fs.writeFileSync(OUTPUT,text);console.log('Wind tree profiles: '+Object.keys(build()).length+' maps, author files unchanged.');}
module.exports={build,TILE_PARTS};
