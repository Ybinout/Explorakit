// Rebuild the tiny visual ground masks after editing one of these authoritative maps.
// This reads maps only; it never rewrites their Tiled data or artwork.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..'), masks = {};
const aliases = require('../data/game/mapAliases.json').aliases;
for (const name of ['start', 'route1', 'route2', 'ville1_arene']) {
    const map = JSON.parse(fs.readFileSync(path.join(root, 'data/maps', (aliases[name] || name) + '.json'), 'utf8'));
    const collision = map.layers.find(layer => layer.name === 'coll');
    // The leaf layer is a full-map image atlas: even transparent cells have a GID.
    // Its visible pixels occlude impacts naturally in the later foreground pass.
    const covered = map.layers.filter(layer => ['foreground', 'for2', 'change', 'int'].includes(layer.name));
    if (map.width !== 28 || map.height !== 20 || !collision) throw Error('Unexpected weather map: ' + name);
    masks[name] = Array.from({ length: map.height }, (_, y) => Array.from({ length: map.width }, (_, x) => {
        const index = y * map.width + x;
        return collision.data[index] === 0 && covered.every(layer => !layer.data[index]) ? '1' : '0';
    }).join(''));
}
fs.writeFileSync(path.join(root, 'vue-explorakit/src/data/worldRainGround.js'), '// Generated by scripts/generateWorldRainGround.js. Do not edit by hand.\nexport default ' + JSON.stringify(masks, null, 2) + ';\n');
console.log('Ground-only rain masks generated for ' + Object.keys(masks).join(', '));
